"""Generate compact offline talent facts from the reviewed source manifest."""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
data = json.loads((ROOT / 'tools/talent-guide-sources.json').read_text())

def lua(value):
    if isinstance(value, str):
        return json.dumps(value, ensure_ascii=False)
    if isinstance(value, bool):
        return 'true' if value else 'false'
    if isinstance(value, dict):
        return '{' + ','.join('[' + lua(k) + ']=' + lua(v) for k, v in value.items()) + '}'
    if isinstance(value, list):
        return '{' + ','.join(map(lua, value)) + '}'
    if value is None:
        return 'nil'
    return str(value)

profiles = []
for b in data['leveling']:
    counts = {}
    for t in b['chunks']:
        assert counts.get(t['name'], 0) < t['rank'] <= t['max']
        counts[t['name']] = t['rank']
    assert sum(counts.values()) == 51
    profiles.append(dict(classToken=b['class'], spec=b['spec'], mode='Leveling',
                         source=b['url'], chunks=b['chunks'], ordered=True,
                         publisher=b.get('publisher', 'WoW Forever Builds'),
                         status='Community guide' if b.get('publisher') == 'ForeverSpec' else 'Theorycraft', checked=data['checked']))
for b in data['pve']:
    assert sum(t['rank'] for t in b['talents']) == 51
    assert len({t['name'] for t in b['talents']}) == len(b['talents'])
    profiles.append(dict(classToken=b['cls'], spec=b['spec'], mode='PvE',
                         source=b['url'], chunks=b['talents'], ordered=False,
                         role=b['role'], outdated=b['outdated'], updated=b['updated'],
                         publisher='WoW Forever Builds', status='Theorycraft', checked=data['checked']))
assert len(profiles) == 54
assert len({(p['classToken'], p['spec']) for p in profiles if p['ordered']}) == 27
for hybrid in data.get('hybrids', []):
    assert sum(t['rank'] for t in hybrid['chunks']) == 51
    assert all(0 < t['rank'] <= t['max'] for t in hybrid['chunks'])
    profiles.append(hybrid)
out = ROOT / 'TalentGuide/Guides.lua'
out.parent.mkdir(exist_ok=True)
out.write_text('-- Generated by tools/build_talent_guides.py; see SOURCES.md.\nlocal _, A = ...\nA.guides = ' + lua(profiles) + '\n', encoding='utf8')
print(f"Generated 27 leveling routes, 27 PvE spec builds and {len(data.get('hybrids', []))} hybrid profile(s).")
