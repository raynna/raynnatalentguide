"""Generate TalentGuide/Localization.lua from the open Forever talent trees.

The guide routes in Guides.lua are keyed by English talent name, while the
client returns localized spell names. This builds a table that maps every
talent's position in its tree (tree index, row, column) to its English name,
so non-English clients can be matched by position instead of by name.

Source: https://github.com/theforeverguides/wow-forever-data (MIT), file
data/talents.json, derived from beta client data via foreverdiff.com.

Usage:
    python tools/build_talent_positions.py [talents.json]

With no argument the file is downloaded from the repository above.
"""

import json
import sys
import urllib.request

SOURCE = (
    "https://raw.githubusercontent.com/theforeverguides/"
    "wow-forever-data/main/data/talents.json"
)
OUT = "TalentGuide/Localization.lua"

HEADER = '''-- Generated by tools/build_talent_positions.py; do not edit by hand.
--
-- Talent routes are stored with English names, but C_Spell.GetSpellName gives
-- the client's own language. This table identifies each talent by where it
-- sits in its tree (tree, row, column), which is the same in every locale, and
-- hands back the English name the routes expect.
--
-- Tree data: https://github.com/theforeverguides/wow-forever-data (MIT
-- licence), data/talents.json, derived from beta client data via
-- foreverdiff.com and compiled by Forever Guides (theforeverguides.com).
local _, A = ...

-- [CLASS][tree][row][column] = { en = English name, max = maximum rank }
A.talentPositions = {'''

BODY = '''

local function PlayerClass()
    return select(2, UnitClass("player"))
end

-- Is there a table for this character's class?
function A.CanLocalize()
    local class = PlayerClass()
    return class ~= nil and A.talentPositions[class] ~= nil
end

-- Turn coordinates into 1..n indices, stepping by the smallest gap between
-- them, so an empty row or column cannot shift everything after it.
local function Indices(values)
    table.sort(values)
    local step
    for i = 2, #values do
        local gap = values[i] - values[i - 1]
        if gap > 0 and (not step or gap < step) then
            step = gap
        end
    end
    local index = {}
    for _, value in ipairs(values) do
        index[value] = step and (math.floor((value - values[1]) / step + 0.5) + 1) or 1
    end
    return index
end

-- node ID -> { tree, row, column } for the open configuration.
function A.BuildNodePositions(config, info)
    if not (C_Traits and config and info and info.treeIDs and A.CanLocalize()) then
        return nil
    end
    local byGroup, groupOrder = {}, {}
    for _, tree in ipairs(info.treeIDs) do
        for index, group in ipairs(C_Traits.GetGroupDisplayInfoByTreeID(tree) or {}) do
            groupOrder[group.groupID] = index
        end
        for _, id in ipairs(C_Traits.GetTreeNodes(tree) or {}) do
            local node = C_Traits.GetNodeInfo(config, id)
            local groupID = node and (node.groupIDs or {})[1]
            if groupID then
                byGroup[groupID] = byGroup[groupID] or {}
                table.insert(byGroup[groupID], { id = id, x = node.posX or 0, y = node.posY or 0 })
            end
        end
    end
    local positions = {}
    for groupID, list in pairs(byGroup) do
        local xs, ys, seenX, seenY = {}, {}, {}, {}
        for _, node in ipairs(list) do
            if not seenX[node.x] then
                seenX[node.x] = true
                table.insert(xs, node.x)
            end
            if not seenY[node.y] then
                seenY[node.y] = true
                table.insert(ys, node.y)
            end
        end
        local column, row = Indices(xs), Indices(ys)
        for _, node in ipairs(list) do
            positions[node.id] = {
                tree = groupOrder[groupID] or 1,
                row = row[node.y],
                column = column[node.x],
            }
        end
    end
    return positions
end

-- English name for that node. When the node's maximum rank disagrees with the
-- table the tree data is out of date for that talent, so nothing is returned:
-- the addon then reports its usual mismatch instead of pointing at the wrong
-- talent.
function A.EnglishTalentName(position, maxRanks)
    if not position or not position.row or not position.column then
        return nil
    end
    local class = PlayerClass()
    local tree = class and A.talentPositions[class] and A.talentPositions[class][position.tree]
    local row = tree and tree[position.row]
    local talent = row and row[position.column]
    if not talent then
        return nil
    end
    if maxRanks and talent.max and maxRanks ~= talent.max then
        return nil
    end
    return talent.en
end
'''

TOKENS = {
    "Druid": "DRUID", "Hunter": "HUNTER", "Mage": "MAGE", "Paladin": "PALADIN",
    "Priest": "PRIEST", "Rogue": "ROGUE", "Shaman": "SHAMAN",
    "Warlock": "WARLOCK", "Warrior": "WARRIOR",
}


def escape(text):
    return text.replace("\\", "\\\\").replace('"', '\\"')


def main():
    if len(sys.argv) > 1:
        with open(sys.argv[1], encoding="utf-8") as handle:
            data = json.load(handle)
    else:
        with urllib.request.urlopen(SOURCE) as response:
            data = json.loads(response.read().decode("utf-8"))

    lines, count = [HEADER], 0
    for class_name, info in sorted(data["classes"].items()):
        lines.append("    %s = {" % TOKENS[class_name])
        for index, tree in enumerate(info["trees"], 1):
            rows = {}
            for talent in tree["talents"]:
                rows.setdefault(talent["row"], {})[talent["col"]] = (
                    talent["name"], talent["max_rank"],
                )
                count += 1
            lines.append("        { -- %d %s" % (index, tree["name"]))
            for row in sorted(rows):
                cells = ", ".join(
                    '[%d]={en="%s",max=%d}' % (column, escape(name), rank)
                    for column, (name, rank) in sorted(rows[row].items())
                )
                lines.append("            [%d] = { %s }," % (row, cells))
            lines.append("        },")
        lines.append("    },")
    lines.append("}")

    with open(OUT, "w", encoding="utf-8") as handle:
        handle.write("\n".join(lines) + BODY)
    print("wrote %s with %d talents" % (OUT, count))


if __name__ == "__main__":
    main()
